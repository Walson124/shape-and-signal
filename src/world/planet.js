// Collision shapes for props: trunk radius, height, and whether you can stand on top.
const PROP_SHAPE = {
  [PROP.PINE]: [0.45, 10, false], [PROP.BROAD]: [0.55, 9, false], [PROP.ROCK]: [1.45, 1.5, true], [PROP.CACTUS]: [0.5, 4.5, false],
  [PROP.CRYSTAL]: [0.9, 4.5, false], [PROP.SHROOM]: [0.55, 3.4, false], [PROP.DEAD]: [0.35, 5, false], [PROP.ICE]: [0.9, 6, false],
};
const PCELL = 16;
const cellKey = (x, y, z) => `${Math.floor(x / PCELL)},${Math.floor(y / PCELL)},${Math.floor(z / PCELL)}`;
const tC = new THREE.Vector3();
const ZERO_M = new THREE.Matrix4().makeScale(0, 0, 0);

const RES = 32;
const UP = new THREE.Vector3(0, 1, 0);
const tA = new THREE.Vector3();
const tB = new THREE.Vector3();
const tQ = new THREE.Quaternion();
const tM = new THREE.Matrix4();
const d3 = [0, 0, 0];

// A planet or moon: orbit frame -> axial tilt -> spinning surface frame. The
// surface is a cube-sphere quadtree whose chunks are generated by workers.
export class Planet {
  constructor(body, ctx) {
    this.body = body;
    this.ctx = ctx;
    this.key = `${ctx.starKey}:${body.id}`;
    this.R = body.radius;
    this.info = PLANET_INFO[body.type];
    this.orbitGroup = new THREE.Group();
    this.orbitGroup.name = body.id;
    this.tilt = new THREE.Group();
    this.tilt.rotation.z = body.spin.tilt;
    this.spin = new THREE.Group();
    this.orbitGroup.add(this.tilt);
    this.tilt.add(this.spin);
    this.params = {
      key: this.key, type: body.type, seed: body.seed, radius: this.R, amp: body.amp, sea: body.sea,
      city: body.sites.city, outposts: [...body.sites.outposts, ...(body.sites.towns || [])], ruins: body.sites.ruins || [],
    };
    this.atmoR = body.atmo ? this.R * (1 + body.atmo.height) : this.R + body.amp * 1.5 + 200;
    this.soi = Math.max(this.atmoR * 2.4, this.R * 3.5);
    this.worldPos = new THREE.Vector3();
    this.camLocal = new THREE.Vector3();
    this.details = null;
    this.textures = [];
    this.propHash = new Map();
    this.brokenProps = [];
    this.fallers = [];
    if (body.landable) {
      this.terrain = makeTerrain(this.params);
      this.setupQuadtree();
    }
    if (body.atmo) {
      this.atmo = makeAtmosphere(body);
      this.tilt.add(this.atmo.mesh);
    }
    if (body.ocean && body.landable) {
      this.ocean = makeOcean(body);
      this.spin.add(this.ocean.mesh);
    }
    if (body.clouds && body.landable) {
      this.clouds = makeClouds(body);
      this.spin.add(this.clouds.mesh);
    }
  }

  // ---------------------------------------------------------- gas giants --
  async setupGas() {
    const tex = await texPool.run('planet', { type: 'gas', seed: this.body.seed, w: this.ctx.preset.texRes });
    const map = new THREE.DataTexture(tex.color, tex.w, tex.h, THREE.RGBAFormat);
    map.colorSpace = THREE.SRGBColorSpace;
    map.wrapS = THREE.RepeatWrapping;
    map.generateMipmaps = true;
    map.minFilter = THREE.LinearMipmapLinearFilter;
    map.magFilter = THREE.LinearFilter;
    map.anisotropy = 8;
    map.needsUpdate = true;
    this.textures.push(map);
    this.gasMesh = new THREE.Mesh(new THREE.SphereGeometry(this.R, 128, 64), new THREE.MeshStandardMaterial({ map, roughness: 0.95, metalness: 0, envMapIntensity: 0.1 }));
    this.spin.add(this.gasMesh);
    if (this.body.rings) {
      const ring = await texPool.run('ring', { stops: tex.ringColors, seed: this.body.seed + 3 });
      const rings = makeRings(this.body, ring);
      this.textures.push(rings.tex);
      this.tilt.add(rings.mesh);
    }
  }

  // ------------------------------------------------------------ quadtree --
  setupQuadtree() {
    const pre = this.ctx.preset;
    this.faceArc = (this.R * Math.PI) / 2;
    this.maxLevel = Math.max(3, Math.ceil(Math.log2(this.faceArc / pre.leaf)));
    this.splitK = pre.split;
    this.material = terrainMaterial(0.35);
    // holes and caves: built volume replaces the heightfield where dug
    this.voxMaterial = terrainMaterial(0.35);
    this.digsSys = FEATURES.digging ? new Digs(this) : null;
    if (this.digsSys) this.digsSys.attach(this.material);
    this.propMat = propMaterial();
    this.propGeos = propGeometries();
    this.index = new THREE.BufferAttribute(chunkIndex(RES), 1);
    this.terrainGroup = new THREE.Group();
    this.spin.add(this.terrainGroup);
    this.roots = [0, 1, 2, 3, 4, 5].map((f) => this.makeNode(f, 0, 0, 0, null));
    this.chunkCount = 0;
  }

  makeNode(face, level, x, y, parent) {
    const n = 1 << level;
    cubeToSphere(face, -1 + (2 * (x + 0.5)) / n, -1 + (2 * (y + 0.5)) / n, d3);
    const size = this.faceArc / n;
    return {
      face, level, x, y, parent,
      center: new THREE.Vector3(d3[0], d3[1], d3[2]).multiplyScalar(this.R),
      size, radius: size * 0.8 + this.body.amp, mesh: null, ready: false, requested: false,
      children: null, alive: true, dist: Infinity,
    };
  }

  request(node) {
    if (node.requested) return;
    node.requested = true;
    const job = { params: this.params, face: node.face, level: node.level, x: node.x, y: node.y, res: RES, props: node.level >= this.maxLevel - (this.ctx.preset.split >= 2.4 ? 1 : 0), craters: this.cratersNear(node) };
    texPool.run('chunk', job, { priority: () => node.dist * (1 + node.level * 0.02), cancelled: () => !node.alive }).then((out) => {
      if (!out || !node.alive) return;
      this.buildMesh(node, out);
    }).catch((e) => console.error(e));
  }

  buildMesh(node, out) {
    const geo = new THREE.BufferGeometry();
    geo.setAttribute('position', new THREE.BufferAttribute(out.positions, 3));
    geo.setAttribute('normal', new THREE.BufferAttribute(out.normals, 3));
    geo.setAttribute('color', new THREE.BufferAttribute(out.colors, 3));
    geo.setAttribute('glow', new THREE.BufferAttribute(out.glow, 1));
    geo.setAttribute('ppos', new THREE.BufferAttribute(out.ppos, 3));
    geo.setIndex(this.index);
    geo.boundingSphere = new THREE.Sphere(new THREE.Vector3(), out.radius);
    const mesh = new THREE.Mesh(geo, this.material);
    mesh.position.set(out.center[0], out.center[1], out.center[2]);
    mesh.visible = false;
    node.center.copy(mesh.position);
    node.radius = out.radius;
    node.mesh = mesh;
    node.ready = true;
    const density = settings.get('propDensity') ?? 1;
    if (out.props && out.props.length && density > 0) {
      if (density < 1) {
        // thin the props deterministically
        const kept = [];
        for (let i = 0, k = 0; i < out.props.length; i += 6, k++) if ((k * 7919) % 100 < density * 100) kept.push(...out.props.slice(i, i + 6));
        out.props = kept;
      }
      const byType = new Map();
      for (let i = 0; i < out.props.length; i += 6) {
        const t = out.props[i];
        if (!byType.has(t)) byType.set(t, []);
        byType.get(t).push(i);
      }
      const m = new THREE.Matrix4();
      const s = new THREE.Vector3();
      const yaw = new THREE.Quaternion();
      const instOf = new Map();
      for (const [type, list] of byType) {
        const geoP = this.propGeos[type];
        if (!geoP) continue;
        const inst = new THREE.InstancedMesh(geoP, this.propMat, list.length);
        list.forEach((i, k) => {
          tA.set(out.props[i + 1], out.props[i + 2], out.props[i + 3]);
          tB.copy(tA).add(mesh.position).normalize();
          tQ.setFromUnitVectors(UP, tB);
          yaw.setFromAxisAngle(UP, out.props[i + 5]);
          tQ.multiply(yaw);
          const sc = out.props[i + 4];
          s.set(sc, sc, sc);
          m.compose(tA, tQ, s);
          inst.setMatrixAt(k, m);
          instOf.set(i, [inst, k]);
        });
        inst.computeBoundingSphere();
        mesh.add(inst);
      }
      if (node.level >= this.maxLevel - 1) {
        node.propKeys = [];
        for (let i = 0; i < out.props.length; i += 6) {
          const shape = PROP_SHAPE[out.props[i]];
          if (!shape) continue;
          const sc = out.props[i + 4];
          const base = new THREE.Vector3(out.props[i + 1], out.props[i + 2], out.props[i + 3]).add(mesh.position);
          const io = instOf.get(i);
          const e = { base, up: base.clone().normalize(), r: shape[0] * sc, h: shape[1] * sc, top: shape[2], mesh, inst: io && io[0], k: io ? io[1] : -1, type: out.props[i] };
          const k = cellKey(base.x, base.y, base.z);
          if (!this.propHash.has(k)) this.propHash.set(k, []);
          this.propHash.get(k).push(e);
          node.propKeys.push([k, e]);
        }
      }
    }
    this.terrainGroup.add(mesh);
    this.chunkCount++;
  }

  disposeNode(node) {
    node.alive = false;
    if (node.children) node.children.forEach((c) => this.disposeNode(c));
    node.children = null;
    if (node.propKeys) {
      for (const [k, e] of node.propKeys) {
        e.dead = true;
        const list = this.propHash.get(k);
        if (!list) continue;
        const i = list.indexOf(e);
        if (i >= 0) list.splice(i, 1);
        if (!list.length) this.propHash.delete(k);
      }
      node.propKeys = null;
    }
    if (node.mesh) {
      this.terrainGroup.remove(node.mesh);
      for (const c of node.mesh.children) if (c.isInstancedMesh) c.dispose();
      node.mesh.geometry.dispose();
      node.mesh = null;
      this.chunkCount--;
    }
  }

  setVisible(node, v) {
    if (node.mesh) node.mesh.visible = v;
  }

  hideSubtree(node) {
    if (node.mesh) node.mesh.visible = false;
    if (node.children) node.children.forEach((c) => this.hideSubtree(c));
  }

  horizonVisible(node, cam, D) {
    const Rmin = this.R - this.body.amp * 0.5;
    if (D <= Rmin * 1.0001) return true;
    const cl = node.center.length();
    const cosA = cam.dot(node.center) / (D * cl);
    const ang = Math.acos(Math.max(-1, Math.min(1, cosA)));
    const h1 = Math.acos(Math.min(1, Rmin / D));
    const h2 = Math.acos(Math.min(1, Rmin / (this.R + this.body.amp + 1)));
    return ang <= h1 + h2 + node.radius / this.R;
  }

  visit(node, cam, D, near) {
    node.dist = Math.max(0, cam.distanceTo(node.center) - node.radius);
    if (!node.ready) this.request(node);
    const visible = this.horizonVisible(node, cam, D);
    const want = near && visible && node.level < this.maxLevel && node.dist < node.size * this.splitK * (settings.get('terrainDetail') || 1);
    if (want) {
      if (!node.children) node.children = [0, 1, 2, 3].map((k) => this.makeNode(node.face, node.level + 1, node.x * 2 + (k & 1), node.y * 2 + (k >> 1), node));
      let ready = true;
      for (const c of node.children) {
        if (!c.ready) {
          c.dist = Math.max(0, cam.distanceTo(c.center) - c.radius);
          this.request(c);
          ready = false;
        }
      }
      if (ready) {
        this.setVisible(node, false);
        for (const c of node.children) this.visit(c, cam, D, near);
      } else {
        this.setVisible(node, true);
        for (const c of node.children) this.hideSubtree(c);
      }
    } else {
      if (node.children) {
        for (const c of node.children) this.disposeNode(c);
        node.children = null;
      }
      this.setVisible(node, visible);
    }
  }

  // ------------------------------------------------------ surface queries --
  // Radius of the walkable surface (terrain or liquid) under a local direction.
  floorRadius(dirX, dirY, dirZ) {
    if (!this.terrain) return this.R;
    if (this.craters && this.craters.length) {
      const off = craterOffset(dirX, dirY, dirZ, this.craters);
      if (off) {
        const h = this.terrain.height(dirX, dirY, dirZ) + off;
        const sea = this.terrain.sea;
        return this.R + (sea !== null && h < sea ? sea : h);
      }
    }
    return this.R + this.terrain.floorHeight(dirX, dirY, dirZ);
  }

  // The ground under a point, holes and caves included.
  groundBelow(pos) {
    if (this.digsSys && this.digsSys.inZone(pos)) return this.digsSys.groundBelow(pos);
    const D = pos.length();
    return this.floorRadius(pos.x / D, pos.y / D, pos.z / D);
  }

  solidAt(pos) {
    if (this.digsSys && this.digsSys.inZone(pos)) return this.digsSys.sdf(pos.x, pos.y, pos.z) > 0;
    const D = pos.length();
    return D < this.groundRadius(pos.x / D, pos.y / D, pos.z / D);
  }

  groundRadius(dirX, dirY, dirZ) {
    if (!this.terrain) return this.R;
    return this.R + this.terrain.height(dirX, dirY, dirZ) + (this.craters && this.craters.length ? craterOffset(dirX, dirY, dirZ, this.craters) : 0);
  }

  // ------------------------------------------------------------ craters --
  // Blast a crater into the ground at a local position (planet frame).
  addCrater(local, radius) {
    if (!this.terrain || !this.roots || radius < 2) return;
    const dir = local.clone().normalize();
    // no craters inside city walls
    if (this.details) for (const s of this.details.settlements) if (local.distanceTo(s.group.position) < s.radius + radius) return;
    this.craters = this.craters || [];
    const r = Math.min(80, radius) / this.R;
    const d = Math.min(18, radius * 0.35);
    const near = this.craters.find((c) => dir.x * c.x + dir.y * c.y + dir.z * c.z > Math.cos(c.r * 0.4));
    if (near) {
      near.d = Math.min(near.d + d * 0.4, Math.max(near.d, 22));
      near.r = Math.max(near.r, r);
      near.cos = Math.cos(near.r * 1.6);
    } else {
      this.craters.push({ x: dir.x, y: dir.y, z: dir.z, r, d, cos: Math.cos(r * 1.6) });
      if (this.craters.length > 60) this.craters.shift();
    }
    const reach = radius * 1.6 + 2;
    const visit = (n) => {
      if (!n) return;
      if (n.center.distanceTo(local) > n.radius + reach + n.size * 0.2) return;
      if (n.mesh) this.remesh(n);
      if (n.children) n.children.forEach(visit);
    };
    this.roots.forEach(visit);
  }

  cratersNear(node) {
    if (!this.craters || !this.craters.length) return null;
    const out = [];
    const cdir = node.center.clone().normalize();
    const nodeAng = (node.radius + node.size * 0.2) / this.R;
    for (const c of this.craters) {
      const ang = Math.acos(Math.max(-1, Math.min(1, cdir.x * c.x + cdir.y * c.y + cdir.z * c.z)));
      if (ang < nodeAng + c.r * 1.6) out.push(c);
    }
    return out.length ? out : null;
  }

  // Regenerate a chunk in place (after the ground changed under it).
  remesh(node) {
    if (node.remeshing) {
      node.dirty = true;
      return;
    }
    node.remeshing = true;
    const job = { params: this.params, face: node.face, level: node.level, x: node.x, y: node.y, res: RES, props: node.level >= this.maxLevel - (this.ctx.preset.split >= 2.4 ? 1 : 0), craters: this.cratersNear(node) };
    texPool.run('chunk', job, { priority: () => -1, cancelled: () => !node.alive }).then((out) => {
      node.remeshing = false;
      if (!out || !node.alive || !node.mesh) return;
      const old = node.mesh, oldKeys = node.propKeys;
      node.mesh = null;
      node.propKeys = null;
      this.buildMesh(node, out);
      node.mesh.visible = old.visible;
      this.dropProps(oldKeys);
      this.terrainGroup.remove(old);
      for (const c of old.children) if (c.isInstancedMesh) c.dispose();
      old.geometry.dispose();
      this.chunkCount--;
      if (node.dirty) {
        node.dirty = false;
        this.remesh(node);
      }
    }).catch((e) => {
      node.remeshing = false;
      console.error(e);
    });
  }

  dropProps(keys) {
    if (!keys) return;
    for (const [k, e] of keys) {
      e.dead = true;
      const list = this.propHash.get(k);
      if (!list) continue;
      const i = list.indexOf(e);
      if (i >= 0) list.splice(i, 1);
      if (!list.length) this.propHash.delete(k);
    }
  }

  // Push a point out of buildings, walls, furniture, trees and rocks.
  // eye: how far the point sits above the feet (1.7 for the player).
  // Returns a roof radius if the feet rest on top of something.
  collide(local, radius, eye = 0) {
    let roof = null;
    // walls and ceilings of dug holes and caves
    if (this.digsSys && this.digsSys.inZone(local)) {
      const up = local.clone().normalize();
      const body = local.clone().addScaledVector(up, -eye * 0.45);
      const before = body.clone();
      if (this.digsSys.push(body, radius * 0.9)) local.add(body.sub(before));
      this.digsSys.push(local, radius * 0.6);
    }
    if (this.details) {
      for (const s of this.details.settlements) {
        if (local.distanceTo(s.group.position) > s.radius * 1.3 + 200) continue;
        for (const c of s.colliders) {
          tA.subVectors(local, c.pos);
          const along = tA.dot(c.up);
          const feet = along - eye;
          if (along < -2 || feet > c.height + 0.5) continue;
          tB.copy(tA).addScaledVector(c.up, -along);
          const hd = tB.length();
          if (hd < c.radius + radius) {
            if (feet > c.height - Math.min(3, Math.max(0.8, c.height * 0.2))) {
              roof = Math.max(roof ?? 0, c.pos.length() + c.height);
            } else if (hd > 0.001) {
              local.addScaledVector(tB.divideScalar(hd), c.radius + radius - hd);
            }
          }
        }
        const r2 = s.collideBoxes(local, radius, eye);
        if (r2 !== null) roof = Math.max(roof ?? 0, r2);
      }
      for (const e of this.details.ruins) {
        const s = e.obj;
        if (!s || local.distanceTo(s.group.position) > s.radius * 1.4 + 100) continue;
        for (const c of s.colliders) {
          tA.subVectors(local, c.pos);
          const along = tA.dot(c.up);
          const feet = along - eye;
          if (along < -2 || feet > c.height + 0.5) continue;
          tB.copy(tA).addScaledVector(c.up, -along);
          const hd = tB.length();
          if (hd < c.radius + radius) {
            if (feet > c.height - Math.min(3, Math.max(0.8, c.height * 0.2))) roof = Math.max(roof ?? 0, c.pos.length() + c.height);
            else if (hd > 0.001) local.addScaledVector(tB.divideScalar(hd), c.radius + radius - hd);
          }
        }
      }
    }
    // props near the point
    if (this.propHash.size) {
      const cx = Math.floor(local.x / PCELL), cy = Math.floor(local.y / PCELL), cz = Math.floor(local.z / PCELL);
      for (let ix = cx - 1; ix <= cx + 1; ix++) {
        for (let iy = cy - 1; iy <= cy + 1; iy++) {
          for (let iz = cz - 1; iz <= cz + 1; iz++) {
            const list = this.propHash.get(`${ix},${iy},${iz}`);
            if (!list) continue;
            for (const e of list) {
              if (!e.mesh.visible || e.broken) continue;
              tA.subVectors(local, e.base);
              const along = tA.dot(e.up);
              const feet = along - eye;
              if (along < -1.5 || feet > e.h + 0.3) continue;
              tC.copy(tA).addScaledVector(e.up, -along);
              const hd = tC.length();
              if (hd >= e.r + radius) continue;
              if (e.top && feet > e.h - 0.6) {
                roof = Math.max(roof ?? 0, e.base.length() + e.h);
              } else if (hd > 0.001) {
                local.addScaledVector(tC.divideScalar(hd), e.r + radius - hd);
              }
            }
          }
        }
      }
    }
    return roof;
  }

  // Break trees and rocks near a planet-local point. Trees topple away from
  // dir; everything regrows a few minutes later. Returns what broke.
  breakProps(local, radius, dir) {
    if (!this.propHash.size) return [];
    const out = [];
    const now = performance.now() / 1000;
    const reach = Math.ceil(radius / PCELL) + 1;
    const cx = Math.floor(local.x / PCELL), cy = Math.floor(local.y / PCELL), cz = Math.floor(local.z / PCELL);
    for (let ix = cx - reach; ix <= cx + reach; ix++) {
      for (let iy = cy - reach; iy <= cy + reach; iy++) {
        for (let iz = cz - reach; iz <= cz + reach; iz++) {
          const list = this.propHash.get(`${ix},${iy},${iz}`);
          if (!list) continue;
          for (const e of list) {
            if (e.broken || !e.inst || !e.mesh.visible) continue;
            tA.subVectors(local, e.base);
            const along = tA.dot(e.up);
            if (along < -3 || along > e.h + radius) continue;
            tA.addScaledVector(e.up, -along);
            if (tA.length() > radius + e.r) continue;
            e.broken = true;
            e.regrowAt = now + 200 + Math.random() * 120;
            e.mat = e.mat || new THREE.Matrix4();
            e.inst.getMatrixAt(e.k, e.mat);
            e.inst.setMatrixAt(e.k, ZERO_M);
            e.inst.instanceMatrix.needsUpdate = true;
            this.brokenProps.push(e);
            if (!e.top && this.propGeos[e.type]) {
              // a falling copy of the tree
              const fm = new THREE.Mesh(this.propGeos[e.type], this.propMat);
              e.mat.decompose(fm.position, fm.quaternion, fm.scale);
              e.mesh.add(fm);
              let away = dir ? dir.clone() : tA.clone();
              away.addScaledVector(e.up, -away.dot(e.up));
              if (away.lengthSq() < 1e-6) away.set(1, 0, 0).addScaledVector(e.up, -e.up.x);
              away.normalize();
              const axis = new THREE.Vector3().crossVectors(e.up, away).normalize();
              this.fallers.push({ mesh: fm, axis, q0: fm.quaternion.clone(), t: 0, s0: fm.scale.x, parent: e.mesh });
            }
            out.push({ pos: e.base.clone().addScaledVector(e.up, Math.min(e.h, 3)), type: e.type, top: e.top });
          }
        }
      }
    }
    return out;
  }

  updateBroken(dt) {
    for (let i = this.fallers.length - 1; i >= 0; i--) {
      const f = this.fallers[i];
      f.t += dt;
      const k = Math.min(1, f.t / 1.3);
      const ang = 1.5 * k * k;
      f.mesh.quaternion.copy(f.q0).premultiply(tQ.setFromAxisAngle(f.axis, ang));
      if (f.t > 6) f.mesh.scale.setScalar(f.s0 * Math.max(0, 1 - (f.t - 6) / 1.5));
      if (f.t > 7.5 || !f.parent.parent) {
        f.parent.remove(f.mesh);
        this.fallers.splice(i, 1);
      }
    }
    if (!this.brokenProps.length) return;
    const now = performance.now() / 1000;
    for (let i = this.brokenProps.length - 1; i >= 0; i--) {
      const e = this.brokenProps[i];
      if (e.dead) { this.brokenProps.splice(i, 1); continue; }
      if (now > e.regrowAt && e.base.distanceTo(this.camLocal) > 60) {
        e.inst.setMatrixAt(e.k, e.mat);
        e.inst.instanceMatrix.needsUpdate = true;
        e.broken = false;
        this.brokenProps.splice(i, 1);
      }
    }
  }

  // Settlement objects are built when you come near and freed when you leave.
  allSites() {
    const s = this.body.sites;
    return [s.city, ...(s.towns || []), ...s.outposts].filter(Boolean);
  }

  ensureSettlement(site) {
    this.buildDetails();
    const entry = this.details.sites.find((e) => e.site === site);
    if (!entry) return null;
    if (!entry.obj) {
      entry.obj = buildSettlement(site, this.R, { crowd: (this.ctx.preset.crowd ?? 1) * (settings.get('crowds') ? 1 : 0) });
      this.spin.add(entry.obj.group);
      this.refreshSettlements();
    }
    return entry.obj;
  }

  ensureRuin(i) {
    this.buildDetails();
    const e = this.details.ruins[i];
    if (!e) return null;
    if (!e.obj) {
      e.obj = buildRuinField(e.site, this);
      this.spin.add(e.obj.group);
      this.refreshSettlements();
    }
    return e.obj;
  }

  refreshSettlements() {
    const d = this.details;
    d.settlements = d.sites.filter((e) => e.obj).map((e) => e.obj);
    d.services = [...(d.campServices || [])];
    for (const e of d.ruins || []) if (e.obj) d.services.push(...e.obj.services);
    for (const s of d.settlements) d.services.push(...s.services);
  }

  buildDetails() {
    if (this.details || !this.body.landable) return;
    const d = { sites: [], settlements: [], pois: [], services: [], ruins: [] };
    for (const site of this.body.sites.ruins || []) d.ruins.push({ site, dir: new THREE.Vector3(site.x, site.y, site.z).normalize(), obj: null });
    for (const site of this.allSites()) {
      const dir = new THREE.Vector3(site.x, site.y, site.z).normalize();
      // a light pillar marks every settlement from afar
      const col = site.size === 'outpost' ? 0x7affd8 : site.main ? 0xffe44d : 0x3ef2ff;
      const beacon = new THREE.Sprite(new THREE.SpriteMaterial({ map: glowTexture(), color: new THREE.Color(col).multiplyScalar(1.6), blending: THREE.AdditiveBlending, depthWrite: false, transparent: true }));
      beacon.position.copy(dir).multiplyScalar(this.R + site.height + 60);
      beacon.scale.setScalar(site.radius * 0.9);
      this.spin.add(beacon);
      d.sites.push({ site, dir, obj: null, beacon });
    }
    const accent = this.body.type === 'toxic' ? 0xb4ff4a : this.body.type === 'lava' ? 0xffa040 : this.body.type === 'crystal' ? 0xb98cff : 0x3ef2ff;
    for (const poi of this.body.pois) {
      let dir = new THREE.Vector3(...poi.dir).normalize();
      // keep points of interest on dry land and out of settlements
      for (let k = 0; k < 16; k++) {
        const h = this.terrain.height(dir.x, dir.y, dir.z);
        const wet = this.terrain.sea !== null && h < this.terrain.sea + this.body.amp * 0.02;
        if (!wet && !this.terrain.inSite(dir.x, dir.y, dir.z, 1.6)) break;
        dir.add(new THREE.Vector3(Math.sin(poi.seed + k * 7.1), Math.cos(poi.seed * 0.7 + k * 3.3), Math.sin(poi.seed * 0.3 + k * 5.7)).multiplyScalar(0.12)).normalize();
      }
      const obj = buildPoi(poi, accent);
      const r = this.groundRadius(dir.x, dir.y, dir.z);
      obj.group.position.copy(dir).multiplyScalar(r);
      obj.group.quaternion.setFromUnitVectors(UP, dir);
      this.spin.add(obj.group);
      d.pois.push({ poi, obj, pos: obj.group.position.clone(), up: dir.clone(), alive: true, hp: 1 });
      if (obj.trader) {
        d.campServices = d.campServices || [];
        const tp = obj.trader.clone().applyQuaternion(obj.group.quaternion).add(obj.group.position);
        const td = tp.clone().normalize();
        tp.copy(td).multiplyScalar(this.floorRadius(td.x, td.y, td.z) + 1.6);
        d.campServices.push({ kind: 'camp', name: 'Hunters Camp Trader', pos: tp, range: 9, city: null });
      }
    }
    this.details = d;
    this.refreshSettlements();
  }

  disposeDetails() {
    if (!this.details) return;
    for (const e of this.details.sites) {
      if (e.obj) {
        this.spin.remove(e.obj.group);
        e.obj.dispose();
      }
      this.spin.remove(e.beacon);
      e.beacon.material.dispose();
    }
    for (const e of this.details.ruins || []) {
      if (!e.obj) continue;
      this.spin.remove(e.obj.group);
      e.obj.dispose();
    }
    for (const p of this.details.pois) {
      this.spin.remove(p.obj.group);
      p.obj.group.traverse((o) => {
        if (o.geometry) o.geometry.dispose();
        if (o.material && !o.isSprite) o.material.dispose();
      });
    }
    this.details = null;
  }

  // -------------------------------------------------------------- update --
  prepare(t) {
    this.spin.rotation.y = (t / this.body.spin.period) * Math.PI * 2;
  }

  update(dt, t, camera, sunWorld) {
    this.spin.getWorldPosition(this.worldPos);
    camera.getWorldPosition(tA);
    this.camWorld = (this.camWorld || new THREE.Vector3()).copy(tA);
    this.camLocal.copy(tA);
    this.spin.worldToLocal(this.camLocal);
    const D = this.camLocal.length();
    if (this.roots) {
      const near = D < this.R * 40;
      for (const r of this.roots) this.visit(r, this.camLocal, D, near);
    }
    if (D < this.R * 6) this.buildDetails();
    else if (D > this.R * 10) this.disposeDetails();
    if (this.details) {
      let changed = false;
      for (const e of this.details.sites) {
        const center = tB.copy(e.dir).multiplyScalar(this.R + e.site.height);
        const d = center.distanceTo(this.camLocal);
        if (!e.obj && d < 6500) {
          e.obj = buildSettlement(e.site, this.R, { crowd: (this.ctx.preset.crowd ?? 1) * (settings.get('crowds') ? 1 : 0) });
          addCompiled(this.spin, e.obj.group);
          changed = true;
        } else if (e.obj && d > 9500) {
          cancelAdd(e.obj.group);
          this.spin.remove(e.obj.group);
          e.obj.dispose();
          e.obj = null;
          changed = true;
        }
        e.beacon.visible = d > 2500;
        e.beacon.material.opacity = Math.min(1, (d - 2500) / 4000);
      }
      for (const e of this.details.ruins) {
        const d = tB.copy(e.dir).multiplyScalar(this.R).distanceTo(this.camLocal);
        if (!e.obj && d < 3200) {
          e.obj = buildRuinField(e.site, this);
          addCompiled(this.spin, e.obj.group);
          changed = true;
        } else if (e.obj && d > 4800) {
          cancelAdd(e.obj.group);
          this.spin.remove(e.obj.group);
          e.obj.dispose();
          e.obj = null;
          changed = true;
        }
        if (e.obj) e.obj.update(dt);
      }
      if (changed) this.refreshSettlements();
      for (const s of this.details.settlements) s.update(dt, this.camLocal);
      for (const p of this.details.pois) if (p.alive) p.obj.update(dt);
    }
    if (this.atmo) {
      const u = this.atmo.uniforms;
      u.uPlanetView.value.copy(this.worldPos).applyMatrix4(camera.matrixWorldInverse);
      u.uSunDir.value.subVectors(sunWorld, this.worldPos).normalize().transformDirection(camera.matrixWorldInverse);
      const inside = tA.distanceTo(this.worldPos) < this.atmoR;
      const side = inside ? THREE.BackSide : THREE.FrontSide;
      if (this.atmo.mat.side !== side) {
        this.atmo.mat.side = side;
        this.atmo.mat.needsUpdate = true;
      }
    }
    if (this.clouds) {
      this.clouds.uniforms.uTime.value = t;
      this.clouds.uniforms.uSunDir.value.subVectors(sunWorld, this.worldPos).normalize().transformDirection(camera.matrixWorldInverse);
    }
    if (this.ocean) this.ocean.time.value = t;
    this.updateBroken(dt);
  }

  // Local "sky" state for fog and lighting when the camera is inside the atmosphere.
  skyState(sunWorld) {
    const D = this.camLocal.length();
    if (!this.body.atmo || D > this.atmoR) return null;
    const alt = Math.max(0, D - this.R) / (this.atmoR - this.R);
    tA.subVectors(sunWorld, this.worldPos).normalize();
    tB.subVectors(this.camWorld, this.worldPos).normalize();
    const elev = tA.dot(tB);
    const day = THREE.MathUtils.smoothstep(elev, -0.2, 0.25);
    const c = this.body.atmo.color;
    return { alt, day, elev, color: new THREE.Color(c[0] * 0.55, c[1] * 0.6, c[2] * 0.7) };
  }

  dispose() {
    this.disposeDetails();
    if (this.roots) this.roots.forEach((r) => this.disposeNode(r));
    this.orbitGroup.traverse((o) => {
      if (o.geometry && o.geometry !== this.index) o.geometry.dispose();
      if (o.material && !o.isSprite) o.material.dispose?.();
    });
    for (const tx of this.textures) tx.dispose();
    this.material?.dispose();
    this.propMat?.dispose();
  }
}
